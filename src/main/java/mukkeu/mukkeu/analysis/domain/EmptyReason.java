package mukkeu.mukkeu.analysis.domain;

/**
 * 결과가 비었을 때 그 이유. 카드로는 표현할 수 없는 유일한 정보다.
 *
 * 서버는 조건을 임의로 완화하지 않는다(0개면 0개로 돌려준다). 그래서 왜 0개인지
 * 말해주지 않으면 사용자는 빈 화면만 보고 버그로 오해한다.
 * 프론트가 값마다 고정 문구를 매핑해 빈 화면을 채운다.
 *
 * 값은 "싸게 확실히 판별되는 것" 만 둔다. 맵기·고기 조건은 벡터 검색 SQL 안에서
 * 걸러지므로, 그것 때문에 0개인지 아닌지를 알려면 조건 없이 한 번 더 검색해야 한다.
 * 임베딩 왕복이 한 번 더 드는 값이라 추측으로 채우지 않고 NO_SIMILAR_MENU 로 합쳤다.
 */
public enum EmptyReason {

	/** 반경 5km 안에 가게 자체가 없다. */
	NO_NEARBY,

	/** 반경 안에는 있지만 배달시간 조건에 전부 걸렸다. */
	DELIVERY_TIME_FILTERED,

	/** 가게는 있지만 설정한 조건 안에서 비슷한 메뉴를 파는 곳을 찾지 못했다. */
	NO_SIMILAR_MENU
}
