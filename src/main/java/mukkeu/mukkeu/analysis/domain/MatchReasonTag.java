package mukkeu.mukkeu.analysis.domain;

/**
 * 추천 근거 태그. 카드 하나에 왜 이걸 골랐는지를 표시한다.
 *
 * ★ 선언 순서가 곧 우선순위다. 한 카드에 여러 개가 걸리면 위에 있는 것부터 채택한다.
 *
 * OPTION_MATCH 를 TASTE_SIMILAR 보다 위에 둔 이유는 검증 가능성이다.
 * 옵션 일치는 "분모자 넣은 거 맞죠?" 처럼 사용자가 영상과 대조해 확인할 수 있는 사실이지만,
 * 유사도 1등은 우리 벡터 점수라 사용자가 확인할 방법이 없다. 확인되는 근거가 신뢰를 더 준다.
 *
 * ★ 태그는 "우리가 왜 이걸 골랐나" 의 근거여야 한다. 가게의 좋은 속성 아무거나가 아니다.
 *   평점·리뷰 수·배달비는 AnalysisService 랭킹 어디에도 쓰이지 않으므로 태그로 쓰지 않는다.
 *   "별점이 높아서 추천했어요" 는 사실이 아니다. 랭킹에 넣게 되면 그때 태그도 같이 만든다.
 *
 * PREFERENCE_FIT 같은 태그는 두지 않는다. 응답에 실린 후보는 전부 맵기·고기·배달시간
 * 조건을 통과한 것들이라 모든 카드에 참이고, 그러면 정보량이 0 이다.
 */
public enum MatchReasonTag {

	/** 영상에 나온 브랜드의 지점 그대로. exactMatches 카드에만 붙는다. */
	EXACT_MATCH,

	/** 영상에서 언급된 옵션이 이 가게 메뉴에 실제로 있어 켜졌다. */
	OPTION_MATCH,

	/** 그 요리 후보 중 score 1등. 후보가 2개 이상일 때만 붙인다(비교 대상이 없으면 공허하다). */
	TASTE_SIMILAR,

	/** 그 요리 후보 중 거리 상위 2위 이내이면서 절대 기준(1.5km) 안. 둘 다 만족해야 한다. */
	DISTANCE
}
